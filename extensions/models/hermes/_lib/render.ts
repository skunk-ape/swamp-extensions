/** Everything one bot contributes to the repository. */
export function renderBot(b: Bot): RenderedFile[] {
  const out = [
    // Both platforms' profiles, for the same reason as both platforms' unit
    // files — and here it matters more: these two files say genuinely
    // different things, and installing the wrong one removes the boundary.
    renderProfileFor(b, "darwin"),
    renderProfileFor(b, "linux"),
    renderEnvLib(b),
    // Both supervisors, always. See renderUnit for why this is not conditional
    // on the host.
    renderPlist(b),
    renderUnit(b),
  ];
  if (b.entrypoints.includes("gateway")) out.push(renderGateway(b));
  if (b.entrypoints.includes("chat")) out.push(renderChat(b));
  out.push(renderVaultLib());
  return out.sort((a, z) => a.path.localeCompare(z.path));
}
