/** Identical for every bot, so it is rendered once. */
export function renderVaultLib(): RenderedFile {
  return {
    path: "bin/lib-vault.sh",
    kind: "shared",
    mode: 0o644,
    content: `# Shared vault read. Sourced, not executed.
#
# GENERATED by @skunk-ape/hermes/bot. Identical for every bot on this pattern,
# so it is rendered once rather than per bot. Do not edit; edit the declaration
# and re-render.
#
# Capturing stderr into the value (\`2>&1\`) is the bug this exists to prevent:
# swamp writes warnings to stderr, and a warning line concatenated onto a token
# produces a credential that looks right and fails with an unrelated error — an
# InvalidURL from a newline, not an auth failure.
#
# read_secret <vault> <key>  -> prints the trimmed secret, or fails with a
#                               diagnostic built from stderr alone.
read_secret() {
  local vault="$1" key="$2" value status errfile
  errfile="$(mktemp)"
  value="$(swamp vault read-secret "$vault" "$key" -y 2>"$errfile")"
  status=$?
  if [ $status -ne 0 ]; then
    echo "could not read '$key' from vault '$vault'." >&2
    echo "  swamp said: $(tail -1 "$errfile" | cut -c1-160)" >&2
    rm -f "$errfile"
    return 1
  fi
  rm -f "$errfile"
  # Trim leading/trailing whitespace, including any trailing newline.
  printf '%s' "$value" | tr -d '\\r\\n' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//'
}
`,
  };
}

// ---------------------------------------------------------------------------
// Per-bot environment library
// ---------------------------------------------------------------------------

export function renderEnvLib(b: Bot): RenderedFile {
  const wd = workdirOf(b);
  const content =
    `# ${b.displayName}'s runtime environment. Sourced, not executed.
#
${comment(GENERATED(b.slug))}
#
# Every entrypoint sources this, so the two cannot drift. That matters more here
# than it looks: a terminal session that quietly diverged from the gateway's
# environment would be a second agent wearing the same name with different
# boundaries.
#
# Expects REPO to be set by the caller. Exports WORKDIR and the full environment.

${b.slug.replace(/-/g, "_")}_env() {
  REPO="$(cd "$(dirname "$0")/.." && pwd)"
  WORKDIR="\${${homeEnvVar(b)}:-${wd}}"
${note(b.notes.vault)}  VAULT="\${VAULT:-${b.vault}}"
  # shellcheck source=lib-vault.sh
  . "$REPO/bin/lib-vault.sh"
  KEY="\${KEY:-${b.secretKeys.anthropic}}"

  if [ -z "\${ANTHROPIC_API_KEY:-}" ]; then
    ANTHROPIC_API_KEY="$(cd "$REPO" && read_secret "$VAULT" "$KEY")" || exit 1
    export ANTHROPIC_API_KEY
  fi

${note(b.notes.telegram)}  if [ -z "\${TELEGRAM_BOT_TOKEN:-}" ]; then
    if TELEGRAM_BOT_TOKEN="$(cd "$REPO" && read_secret "$VAULT" ${b.secretKeys.telegram})"; then
      export TELEGRAM_BOT_TOKEN
    else
      echo "warning: Telegram will not connect" >&2
    fi
  fi
  export TELEGRAM_ALLOWED_USERS="\${TELEGRAM_ALLOWED_USERS:-${
      b.telegram.allowedUsers.join(",")
    }}"
${
      note(b.notes.homeChannel)
    }  export TELEGRAM_HOME_CHANNEL="\${TELEGRAM_HOME_CHANNEL:-${b.telegram.homeChannel}}"
  export TELEGRAM_HOME_CHANNEL_NAME="\${TELEGRAM_HOME_CHANNEL_NAME:-${b.telegram.homeChannelName}}"

  # Everything the toolchain writes must land inside the workdir or the sandbox
  # denies it. UV_PYTHON_INSTALL_DIR is the one that bites on a fresh install:
  # without it uv points the venv at the shared interpreter under
  # ~/.local/share/uv, outside the workdir, and the gateway cannot exec its own
  # python. Copying the interpreter in does not fix it — uv's pythons resolve
  # sys.prefix back to their original install path.
  export HERMES_HOME="$WORKDIR/hermes"
  export UV_CACHE_DIR="$WORKDIR/hermes/cache/uv"
  export UV_PYTHON_INSTALL_DIR="$WORKDIR/hermes/python"
  export NPM_CONFIG_CACHE="$WORKDIR/hermes/cache/npm"

  # Pin the terminal's working directory inside the sandbox. Hermes resolves it
  # via _safe_getcwd() (tools/terminal_tool_config.py), which returns os.getcwd()
  # but falls back to $HOME on PermissionError/FileNotFoundError — and $HOME is
  # outside the workdir. The sandbox lets a shell chdir there but not getcwd
  # from it, so on that fallback every command's output is prefixed with
  #   shell-init: error retrieving current directory: getcwd: ...
  # which broke write_file's post-write hash check: it read the first token of
  # the combined stream as the digest and reported a false "the write did not
  # persist correctly" on good writes (fixed upstream in seth/hermes-agent
  # fix/write-verify-digest-parsing; PR NousResearch#105277). TERMINAL_CWD
  # outranks getcwd entirely *and* is the first fallback inside _safe_getcwd,
  # so one variable pins both paths.
  export TERMINAL_CWD="$WORKDIR"

${note(b.notes.funes)}  #
  # FUNES_HOME and HF_HOME both default under $HOME, outside the workdir, so
  # without these the per-turn hook resolves the *host's* funes memory and dies
  # with "Operation not permitted" on every turn. A post_llm_call hook inherits
  # this environment and inherits the sandbox, so setting them here is what puts
  # funes inside the box.
  #
  # <workdir>/funes, not <workdir>/hermes/funes: a Hermes reinstall rebuilds
  # hermes/, and the memory should outlive that. It is the bot's, not Hermes
  # runtime state.
  export FUNES_HOME="$WORKDIR/funes"
  export HF_HOME="$WORKDIR/funes/hf"
${
      b.funes.hfOffline
        ? `  # Offline: if the embedding cache is somehow incomplete, fail loudly here
  # rather than reach for a domain the sandbox will refuse anyway.
  export HF_HUB_OFFLINE=1\n`
        : ""
    }  mkdir -p "$WORKDIR/funes/hf"

  # funes is staged inside the workdir rather than used from ~/.local/bin. That
  # host path happens to be readable from inside the sandbox, but that is a
  # property of nono's default groups, not something the profile asks for — and
  # a \`funes update\` out there would silently change the binary in here.
  export PATH="$WORKDIR/tools:$PATH"

  # The Telegram adapter writes to the XDG state dir, which defaults to
  # ~/.local/state — outside the sandbox. These are redirected into the workdir,
  # but they are exported for the *inner* process only (see the sh -c in each
  # entrypoint), not here: nono keeps its own state root under
  # $XDG_STATE_HOME/nono and reads profiles from $XDG_CONFIG_HOME/nono, so
  # setting them before nono runs makes it refuse the grant ("overlaps protected
  # nono state root") and lose its profiles.
  mkdir -p "$WORKDIR/hermes/xdg/state" "$WORKDIR/hermes/xdg/data" \\
           "$WORKDIR/hermes/xdg/cache" "$WORKDIR/hermes/xdg/config" \\
           "$WORKDIR/hermes/cache/scratch"
}
`;
  return {
    path: `bin/lib-${b.slug}-env.sh`,
    content,
    kind: "envlib",
    mode: 0o644,
  };
}

// ---------------------------------------------------------------------------
// The inner shell
// ---------------------------------------------------------------------------

/**
 * One shape for every entrypoint. `$1` is the workdir; anything after it is the
 * hermes_cli argv.
 *
 * The XDG exports happen INSIDE here rather than in the launcher because nono
 * keeps its own state root under $XDG_STATE_HOME/nono: setting them before nono
 * runs makes it refuse the grant and lose its profiles.
 *
 * TMPDIR is here for the same reason the XDG ones are: the default is outside
 * the workdir. macOS hands every process a per-user TMPDIR; Linux leaves it
 * unset, and SQLite then walks /var/tmp, /usr/tmp, /tmp and takes the first
 * that passes access(2) — which Landlock does not mediate — so it picks
 * /var/tmp, is refused at open, and reports "unable to open database file".
 * Only turns large enough to spill to a temp file fail, so after the Linux
 * cutover Apalone intermittently dropped turns with "session storage could not
 * be written". `hermes/cache/scratch` is where upstream points TMPDIR when it
 * is unset, so an upgrade does not move it.
 */
function inner(argv: string): string {
  return `/bin/sh -c '
      W="$1"; shift
      export XDG_STATE_HOME="$W/hermes/xdg/state"
      export XDG_DATA_HOME="$W/hermes/xdg/data"
      export XDG_CACHE_HOME="$W/hermes/xdg/cache"
      export XDG_CONFIG_HOME="$W/hermes/xdg/config"
      export TMPDIR="$W/hermes/cache/scratch"
      exec "$W/hermes/hermes-agent/venv/bin/python" -m hermes_cli.main ${argv}
    '`;
}

// ---------------------------------------------------------------------------
// Gateway entrypoint
// ---------------------------------------------------------------------------

export function renderGateway(b: Bot): RenderedFile {
  const fn = `${b.slug.replace(/-/g, "_")}_env`;
  const ports = b.mcps.map((m) => m.port).sort((x, y) => x - y);

  // launchd has no ordering between jobs, so a gateway that starts before its
  // MCPs registers no tools at all and stays that way until something bounces
  // it. The wait is bounded and then proceeds anyway: a bot with no tools is
  // better than a bot that never starts.
  const portWait = ports.length
    ? `
# launchd has no ordering between agents, so a gateway that wins the race
# registers no tools at all. systemd does have ordering, and it is still not
# enough: \`After=\` sequences *starts*, not readiness, so the MCP process can
# exist without yet listening. The wait is needed on both platforms.
#
# The probe is bash's own /dev/tcp rather than \`nc\`, which is absent on a
# default Debian or Fedora install and, where it is present, may be a flavour
# whose -z does something else. This needs no package at all.
PORTS="${ports.join(" ")}"
NPORTS=${ports.length}
for _ in $(seq 1 30); do
  ready=0
  for port in $PORTS; do
    (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null && ready=$((ready + 1))
  done
  [ "$ready" -eq "$NPORTS" ] && break
  sleep 2
done
[ "\${ready:-0}" -eq "$NPORTS" ] || echo "warning: only $ready/$NPORTS MCP ports up; starting anyway" >&2
`
    : "";

  const content = `#!/usr/bin/env bash
# Start the ${b.displayName} gateway inside its nono sandbox.
#
${comment(GENERATED(b.slug))}
${b.rationale ? "#\n" + comment(b.rationale) + "\n" : ""}#
${comment(RUN_NOT_WRAP)}
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"

# shellcheck source=lib-${b.slug}-env.sh
. "$REPO/bin/lib-${b.slug}-env.sh"
${fn}
${portWait}${b.notes.network ? "\n" + comment(b.notes.network) + "\n" : ""}
# The two profiles are NOT interchangeable: macOS enforces through
# allow_domain + open_port, Linux through connect_port, and each file is inert
# or wrong on the other kernel. Pick by uname rather than by whichever one was
# committed last.
PLATFORM="$(uname -s | tr '[:upper:]' '[:lower:]')"
PROFILE="$REPO/profiles/${b.slug}.$PLATFORM.nono.json"
[ -f "$PROFILE" ] || { echo "no profile at $PROFILE" >&2; exit 1; }

exec nono run -s \\
  --profile "$PROFILE" \\
  --workdir "$WORKDIR" \\
  -- ${inner("gateway run")} _ "$WORKDIR"
`;
  return {
    path: `bin/run-${b.slug}.sh`,
    content,
    kind: "entrypoint",
    mode: 0o755,
  };
}

// ---------------------------------------------------------------------------
// Terminal entrypoint
// ---------------------------------------------------------------------------

export function renderChat(b: Bot): RenderedFile {
  const c = b.chat!;
  const fn = `${b.slug.replace(/-/g, "_")}_env`;
  const content = `#!/usr/bin/env bash
# Talk to ${b.displayName} from a terminal, in the same sandbox the gateway runs in.
#
${comment(GENERATED(b.slug))}
#
#   bin/${b.slug}-chat.sh                 # interactive session
#   bin/${b.slug}-chat.sh -q "..." --oneshot
#   bin/${b.slug}-chat.sh --continue      # pick up the last session
#   bin/${b.slug}-chat.sh --resume <id>   # resume a specific one (see \`sessions\`)
#
# Everything after the script name is passed through to \`hermes chat\`.
#
# This shares HERMES_HOME with the Telegram gateway, so config, SOUL.md, skills,
# state.db, memories/ and the Funes memory are the same. The conversation
# session is separate unless you --resume one; \`sessions list\` run through this
# script shows the gateway's sessions too, so a thread started on the phone can
# be continued here.
#
# It runs under \`nono run\` with the same profile the gateway uses, for the same
# reason. A terminal session is still an agent reading text other people wrote:
# the injection surface does not go away because a human is watching, and an
# unconfined terminal session would be this agent without its boundaries.
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"

# shellcheck source=lib-${b.slug}-env.sh
. "$REPO/bin/lib-${b.slug}-env.sh"
${fn}

# Where the agent starts. nono's --workdir stays $WORKDIR: the profile grants
# $WORKDIR plus any extra paths by absolute path, so pointing --workdir
# elsewhere would put the bot's own Hermes home out of reach.
WORK_IN="\${${c.workInEnvVar}:-${c.workIn}}"

# Default to \`chat\`, but let a bare subcommand through: \`sessions list\` and
# \`memory status\` are useful against the same home.
if [ $# -gt 0 ] && [[ "$1" != -* ]]; then
  SUB=("$@")
else
  SUB=(chat --in "$WORK_IN" "$@")
fi


# The two profiles are NOT interchangeable: macOS enforces through
# allow_domain + open_port, Linux through connect_port, and each file is inert
# or wrong on the other kernel. Pick by uname rather than by whichever one was
# committed last.
PLATFORM="$(uname -s | tr '[:upper:]' '[:lower:]')"
PROFILE="$REPO/profiles/${b.slug}.$PLATFORM.nono.json"
[ -f "$PROFILE" ] || { echo "no profile at $PROFILE" >&2; exit 1; }

exec nono run -s \\
  --profile "$PROFILE" \\
  --workdir "$WORKDIR" \\
  -- ${inner('"$@"')} _ "$WORKDIR" "\${SUB[@]}"
`;
  return {
    path: `bin/${b.slug}-chat.sh`,
    content,
    kind: "entrypoint",
    mode: 0o755,
  };
}

