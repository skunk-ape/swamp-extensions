/**
 * Why every entrypoint uses `nono run` and never `nono wrap`.
 *
 * This is reproduced in every launcher because it is the single mistake that
 * silently voids the network half of a profile, and the failure is invisible:
 * the bot works, and it can also reach everything it was configured not to.
 */
export const RUN_NOT_WRAP =
  `\`nono run\` rather than \`nono wrap\`: wrap applies filesystem confinement only.
The whole \`network\` block — open_port, allow_domain, deny_domain — is INERT
under wrap, because wrap never starts nono's proxy. Under wrap any sandboxed
agent can reach any local service, including another agent's
credential-holding MCPs.

Verified 2026-09-08: under wrap, \`open_port: [8812]\` still reached 8811 and
8813; under run it reached only 8812, and a raw socket to an external IP failed
with PermissionError from sandbox_init rather than a proxy refusal.

wrap was originally chosen for launchd supervision. That concern was unfounded:
nono run propagates the child's exit code (3 -> 3, 0 -> 0), so KeepAlive with
SuccessfulExit=false still means what it says, and SIGTERM to nono takes the
child with it.`;

const GENERATED = (slug: string) =>
  `GENERATED from the ${slug} bot declaration by @skunk-ape/hermes/bot.
Do not edit this file; edit the declaration and re-render.`;

