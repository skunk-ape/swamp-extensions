/**
 * The plist keeps `__REPO__`, `__HOME__` and `__USER__` placeholders so the
 * committed file carries no machine-specific absolute path. The installer
 * substitutes them at load time.
 *
 * KeepAlive/SuccessfulExit=false means what it says here only because the
 * launcher uses `nono run`, which propagates the child's exit code.
 */
export function renderPlist(b: Bot): RenderedFile {
  const content = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
${comment(GENERATED(b.slug), "  ")}
-->
<plist version="1.0">
<dict>
  <key>Label</key>            <string>sh.${b.slug}.gateway</string>
  <key>ProgramArguments</key> <array><string>__REPO__/bin/run-${b.slug}.sh</string></array>
  <key>RunAtLoad</key>        <true/>
  <key>KeepAlive</key>        <dict><key>SuccessfulExit</key><false/></dict>
  <key>ThrottleInterval</key> <integer>10</integer>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key> <string>__HOME__/.local/bin:/etc/profiles/per-user/__USER__/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
    <key>HOME</key> <string>__HOME__</string>
  </dict>
  <key>StandardOutPath</key>  <string>__HOME__/agents/${b.slug}/logs/sh.${b.slug}.gateway.out.log</string>
  <key>StandardErrorPath</key><string>__HOME__/agents/${b.slug}/logs/sh.${b.slug}.gateway.err.log</string>
</dict>
</plist>
`;
  return {
    path: `launchd/sh.${b.slug}.gateway.plist`,
    content,
    kind: "plist",
    mode: 0o644,
  };
}

// ---------------------------------------------------------------------------
// systemd user unit
// ---------------------------------------------------------------------------

/**
 * The Linux equivalent of the plist, and rendered for every bot on every
 * platform.
 *
 * Both unit files are always written, and that is deliberate. Rendering
 * conditionally on the host would make `render --input check=true` — the drift
 * detector, the thing that catches a hand-edited launcher — report the absent
 * platform's files as drift on every run, on both machines. A committed
 * artifact for a platform you are not currently on costs one file and keeps the
 * check honest.
 *
 * The unit is named for the same label launchd uses: `sh.alpha.gateway`
 * becomes `sh.alpha.gateway.service`. Dots are legal in unit names, so the
 * label — and with it the status schema, the fleet report and every reference
 * in the docs — survives the port untouched.
 *
 * `Restart=on-failure` with `RestartSec=10` is `KeepAlive{SuccessfulExit=false}`
 * with `ThrottleInterval=10`, and means what it says for the same reason: the
 * launcher uses `nono run`, which propagates the child's exit code.
 */
export function renderUnit(b: Bot): RenderedFile {
  const label = `sh.${b.slug}.gateway`;
  const content = `# ${b.displayName}'s gateway, as a systemd user unit.
#
${comment(GENERATED(b.slug))}
#
# Installed into ~/.config/systemd/user by \`install\`, which substitutes the
# placeholders below. Requires lingering — \`loginctl enable-linger\` — or the
# user manager and every bot in it stop at logout. \`install\` refuses without
# it rather than let you find out at the next reboot.

[Unit]
Description=${b.displayName} gateway (nono-sandboxed)
Documentation=file://__REPO__/README.md
# Ordering only. The gateway still waits on its MCP ports in the launcher,
# because After= sequences starts and says nothing about readiness.
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=__REPO__/bin/run-${b.slug}.sh
# KeepAlive{SuccessfulExit=false} / ThrottleInterval=10, in systemd's words.
# Honest only because \`nono run\` propagates the child's exit code.
Restart=on-failure
RestartSec=10
# The launcher resolves secrets through swamp and stages funes from ~/.local/bin,
# so both have to be reachable from a unit that inherits almost no environment.
Environment=PATH=__HOME__/.local/bin:/usr/local/bin:/usr/bin:/bin
Environment=HOME=__HOME__
# systemd will not create these; the directory comes from provision.
StandardOutput=append:__HOME__/agents/${b.slug}/logs/${label}.out.log
StandardError=append:__HOME__/agents/${b.slug}/logs/${label}.err.log

[Install]
WantedBy=default.target
`;
  return {
    path: `systemd/${label}.service`,
    content,
    kind: "unit",
    mode: 0o644,
  };
}

