/**
 * Ports the sandbox must reach to talk to anything outside the machine.
 *
 * Only needed on Linux, and only because `connect_port` filters by port rather
 * than by host: restricting loopback to the MCPs would otherwise restrict
 * everything else to those same ports and cut the bot off from the network. A
 * port allowlist of 443/80 is not a host policy — with no `allow_domain` there
 * is no proxy and no host filtering — which is exactly right for a bot whose
 * declared egress is unrestricted, and is why a bot with a NAMED allowlist
 * cannot use this shape at all.
 */
const EGRESS_PORTS = [443, 80];

/**
 * The sandbox, rendered once per platform.
 *
 * Two files, because the two kernels disagree about what a network policy IS
 * and there is no single document that means the right thing on both. Measured
 * on macOS 15 / nono 0.78.0 and kernel 7.2.5 / nono 0.78.0:
 *
 *   macOS    `allow_domain` is what switches enforcement on. With it, `open_port`
 *            is a real connect allowlist. WITHOUT it there is no network
 *            enforcement at all — an undeclared port with a live listener behind
 *            it is reachable, which is the boundary silently disappearing.
 *
 *   Linux    `allow_domain` puts nono in proxy mode, and that proxy denies ALL
 *            direct loopback connect — including ports in `open_port`, and
 *            including with `--open-port`, `--allow-connect-port`, `connect_port`
 *            or `no_proxy` alongside it. Without `allow_domain`, `open_port`
 *            does not restrict anything either; `connect_port` is the key that
 *            does, and it is a genuine per-port Landlock v4 connect allowlist.
 *
 * So on Linux a bot with MCPs gets `connect_port: [...its ports, 443, 80]` and
 * no `allow_domain`: loopback confined to exactly its own MCPs, every other
 * local service refused, egress unrestricted. A bot with no MCPs gets
 * `connect_port: [443, 80]`, which denies all loopback by simply not listing
 * any. A bot with a named egress allowlist needs the proxy to filter by host,
 * so it keeps `allow_domain` and cannot have loopback ports — crossCheck()
 * rejects that combination rather than rendering a promise the kernel will not
 * keep.
 */
export function renderProfileFor(
  b: Bot,
  platform: "darwin" | "linux",
): RenderedFile {
  const unrestricted = b.sandbox.egress.includes("*");

  // On Linux, an unrestricted bot expresses its whole network policy through
  // connect_port. Everything else keeps the proxy.
  const useConnectPort = platform === "linux" && unrestricted;
  const network: Record<string, unknown> = { block: false };
  if (useConnectPort) {
    network.connect_port = [...b.sandbox.openPorts, ...EGRESS_PORTS];
  } else {
    network.allow_domain = b.sandbox.egress;
    network.open_port = b.sandbox.openPorts;
  }

  const profile = {
    meta: {
      name: b.slug,
      version: "1.0.0",
      // nono profiles are strict JSON, so the "this is generated" marker every
      // other artifact carries as a comment has to live in a real field.
      description:
        `${b.summary} For ${platform}; the other platform's file is beside it and they are NOT interchangeable. Requires \`nono run\` — wrap leaves the network block inert. GENERATED by @skunk-ape/hermes/bot: edit the declaration and re-render, not this file.`,
    },
    extends: "default",
    groups: { include: ["git_config"] },
    filesystem: {
      allow: ["$WORKDIR", ...b.sandbox.filesystemAllow],
      unix_socket_subtree_bind: ["$WORKDIR"],
    },
    workdir: { access: "readwrite" },
    network,
  };
  return {
    path: `profiles/${b.slug}.${platform}.nono.json`,
    content: JSON.stringify(profile, null, 2) + "\n",
    kind: "profile",
    mode: 0o644,
  };
}

