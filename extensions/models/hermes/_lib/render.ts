// One declaration in, the whole runtime out.
//
// Everything in this file that is not interpolated from the declaration is
// INVARIANT: it is the same for every bot, it is load-bearing, and most of it
// is a comment explaining a failure that already happened once. Rendering
// hand-written launchers would be a downgrade if it dropped that prose, so the
// templates carry it verbatim and the declaration adds its own per-bot notes on
// top.
//
// The artifacts are deliberately committed to the repository rather than
// rendered at boot. These are security artifacts: a reviewer needs to read the
// real file, and putting a renderer in the boot path would mean a bad render
// takes every bot down at once.
//
// Both supervisors' unit files are rendered on both platforms — a plist and a
// systemd unit for every bot, always. See renderUnit for why that is not
// conditional on the host.

import type { Bot } from "./decl.ts";
import { homeEnvVar, workdirOf } from "./decl.ts";

/**
 * What a rendered file is for.
 *
 * Classifying by role rather than by file extension: `bin/lib-<slug>-env.sh`
 * and `bin/run-<slug>.sh` are both shell, but only one is executed and only one
 * invokes nono, and a check that keyed on `.sh` would apply the wrong rule to
 * both.
 */
export type FileKind =
  /** nono profile. */
  | "profile"
  /** Sourced environment library. Not executable, does not invoke nono. */
  | "envlib"
  /** An executable that puts the agent inside the sandbox. */
  | "entrypoint"
  /** launchd job definition. */
  | "plist"
  /** systemd user unit definition. */
  | "unit"
  /** Rendered identically for every bot. */
  | "shared";

export type RenderedFile = {
  path: string;
  content: string;
  kind: FileKind;
  /** Unix mode. Entrypoints are executable; everything else is not. */
  mode: number;
};

// ---------------------------------------------------------------------------
// Comment helpers
// ---------------------------------------------------------------------------

/** Turn a prose block into shell comments at the given indent. */
export function comment(text: string, prefix = "# "): string {
  return text.split("\n")
    .map((l) => (l.trim() === "" ? prefix.trimEnd() : prefix + l))
    .join("\n");
}

/** A note from the declaration, as a comment block, or nothing at all. */
function note(text: string | undefined, prefix = "  # "): string {
  return text ? comment(text, prefix) + "\n" : "";
}

