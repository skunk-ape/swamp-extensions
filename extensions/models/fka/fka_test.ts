import {
  assert,
  assertEquals,
  assertRejects,
  assertStringIncludes,
  assertThrows,
} from "jsr:@std/assert@1";
import { model, ownedWrappers, workRoot, writeExecutable } from "./fka.ts";

/** The parsed defaults, as a method sees them when nothing overrides. */
function defaults(over: Record<string, unknown> = {}) {
  return model.globalArguments.parse(over);
}

/** Run `body` with the environment temporarily set, restoring whatever was there. */
function withEnv(vars: Record<string, string | null>, body: () => void) {
  const saved = new Map<string, string | undefined>();
  for (const [k, v] of Object.entries(vars)) {
    saved.set(k, Deno.env.get(k));
    if (v === null) Deno.env.delete(k);
    else Deno.env.set(k, v);
  }
  try {
    body();
  } finally {
    for (const [k, v] of saved) {
      if (v === undefined) Deno.env.delete(k);
      else Deno.env.set(k, v);
    }
  }
}

// --- where the workspace lives -------------------------------------------

Deno.test("the workspace defaults to the user's config directory", () => {
  // Not the repository: a wrapper is invoked by bare name, so two repos wrapping
  // one tool would render the same executable name and only one could be on PATH.
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/home/ada/.config/fka");
  });
});

Deno.test("XDG_CONFIG_HOME wins over the home fallback", () => {
  withEnv({ XDG_CONFIG_HOME: "/xdg", HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/xdg/fka");
  });
});

Deno.test("a relative XDG_CONFIG_HOME is ignored rather than trusted", () => {
  // The spec says it must be absolute. Honouring a relative one would put the
  // wrappers somewhere that depends on the working directory of whoever ran the
  // method, which is nobody's intent.
  withEnv({ XDG_CONFIG_HOME: "relative/path", HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/home/ada/.config/fka");
  });
});

Deno.test("an absolute workRoot is used as given", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(
      workRoot("/repo", defaults({ workRoot: "/opt/fka" })),
      "/opt/fka",
    );
  });
});

Deno.test("a relative workRoot is the project-local escape hatch", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(
      workRoot("/repo", defaults({ workRoot: ".fka" })),
      "/repo/.fka",
    );
  });
});

Deno.test("no home and no override refuses rather than guessing", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: null }, () => {
    assertThrows(() => workRoot("/repo", defaults()), Error, "workRoot");
  });
});

// --- wrapper ownership and removal ---------------------------------------
//
// `generate` deletes what `ownedWrappers` returns, so both halves of the
// judgement are worth pinning: what counts as ours, and what does not.

/** A file that looks like a rendered wrapper, because it carries the marker. */
async function wrapper(dir: string, name: string) {
  await Deno.writeTextFile(
    `${dir}/${name}`,
    `#!/bin/sh\n// ${name} — generated by @skunk-ape/fka. Do not edit.\n`,
  );
}

Deno.test("a tool owns its own aliases and its qualified ones", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-safe-gh");
    await wrapper(dir, "fka-write-gh");
    await wrapper(dir, "fka-help-gh-pr");
    assertEquals(
      (await ownedWrappers(dir, "fka", "gh")).sort(),
      ["fka-help-gh-pr", "fka-safe-gh", "fka-write-gh"],
    );
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a tool whose name merely extends ours is not ours", async () => {
  // `fka-safe-gh` is a prefix of `fka-safe-ghi`, and `ghi` is a different tool.
  // Getting this wrong deletes somebody else's wrapper.
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-safe-gh");
    await wrapper(dir, "fka-safe-ghi");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), ["fka-safe-gh"]);
    assertEquals(await ownedWrappers(dir, "fka", "ghi"), ["fka-safe-ghi"]);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a file without the marker is left alone whatever it is called", async () => {
  // bin/ is a directory the operator put on their PATH. A name collision with
  // something they wrote is not a reason to delete their file.
  const dir = await Deno.makeTempDir();
  try {
    await Deno.writeTextFile(`${dir}/fka-safe-gh`, "#!/bin/sh\necho mine\n");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), []);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("an unknown segment is not ours, since the segment set is closed", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-mostly-safe-gh");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), []);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a missing bin directory is empty rather than an error", async () => {
  assertEquals(await ownedWrappers("/nonexistent-fka-bin", "fka", "gh"), []);
});

// --- the method bodies ---------------------------------------------------
//
// These were untested on the grounds that a method body needs a repository and
// a real CLI on PATH. That is true of `discover` and `classify`; it is not true
// of `generate` or `remove`, which need a directory and a review file. They are
// also the two that matter most — one holds the approval gate, the other is the
// only thing in this model that deletes.

/** Render a log template the way a person reading the log would see it. */
function fill(msg: string, props?: Record<string, unknown>): string {
  if (!props) return msg;
  return msg.replace(/\{(\w+)\}/g, (_, k) => String(props[k] ?? `{${k}}`));
}

/** Everything a method body asks of its context, recorded rather than acted on. */
function fakeCtx(repoDir: string, over: Record<string, unknown> = {}) {
  const written: {
    spec: string;
    name: string;
    data: Record<string, unknown>;
  }[] = [];
  const logs: string[] = [];
  return {
    written,
    logs,
    ctx: {
      globalArgs: model.globalArguments.parse({
        workRoot: repoDir,
        denoPath: "/bin/echo",
        ...over,
      }),
      repoDir,
      logger: {
        info: (m: string, p?: Record<string, unknown>) => logs.push(fill(m, p)),
        warning: (m: string, p?: Record<string, unknown>) =>
          logs.push(fill(m, p)),
      },
      writeResource: (
        spec: string,
        name: string,
        data: Record<string, unknown>,
      ) => {
        written.push({ spec, name, data });
        return Promise.resolve({ name });
      },
      createFileWriter: (_spec: string, name: string) => ({
        writeText: () => Promise.resolve({ name }),
      }),
      extensionFile: (p: string) => `${import.meta.dirname}/${p}`,
    },
  };
}

/** The smallest review that generates something. */
function reviewYaml(approved: boolean, command = "list"): string {
  return `approved: ${approved}
cli: demo
binary: /bin/echo
binaryVersion: demo 1.0
prefix: fka
helpOptions: []
wrappers:
  - segment: safe
    name: demo
    purpose: safe demo commands
    prepend: []
    append: []
    admits:
      maxTier: read-safe
    accepts: table
globalOptions: {}
commands:
  - path: [${command}]
    tier: read-safe
    summary: ""
    why: reads
    options: {}
    dropped: {}
`;
}

/** A crawl that saw exactly `list`, and nothing else. */
const surfaceJson = JSON.stringify({
  cli: "demo",
  binary: "/bin/echo",
  binaryVersion: "demo 1.0",
  nodes: [
    {
      path: [],
      ok: true,
      error: "",
      helpText: "",
      helpFlagUsed: "--help",
      parsed: { usage: "", subcommands: [], options: [] },
    },
    {
      path: ["list"],
      ok: true,
      error: "",
      helpText: "",
      helpFlagUsed: "--help",
      parsed: { usage: "", subcommands: [], options: [] },
    },
  ],
});

async function workspaceWith(review: string): Promise<string> {
  const root = await Deno.makeTempDir();
  await Deno.mkdir(`${root}/demo`, { recursive: true });
  await Deno.writeTextFile(`${root}/demo/review.yaml`, review);
  await Deno.writeTextFile(`${root}/demo/surface.json`, surfaceJson);
  return root;
}

Deno.test("generate refuses a table nobody approved", async () => {
  const root = await workspaceWith(reviewYaml(false));
  try {
    const { ctx } = fakeCtx(root);
    let threw = "";
    try {
      await model.methods.generate.execute({ cli: "demo" }, ctx);
    } catch (e) {
      threw = e instanceof Error ? e.message : String(e);
    }
    assertStringIncludes(threw, "not approved");
    // Refused before rendering, not after: nothing reached PATH.
    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), []);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("generate refuses an approved table that the crawl contradicts", async () => {
  // The check that exists because a human edit sits between the table classify
  // validated and the table generate renders.
  const root = await workspaceWith(reviewYaml(true, "invented"));
  try {
    const { ctx } = fakeCtx(root);
    let threw = "";
    try {
      await model.methods.generate.execute({ cli: "demo" }, ctx);
    } catch (e) {
      threw = e instanceof Error ? e.message : String(e);
    }
    assertStringIncludes(threw, "does not match what discover saw");
    assertStringIncludes(threw, "invented");
    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), []);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("generate renders once the table is approved", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    const { ctx, written } = fakeCtx(root);
    await model.methods.generate.execute({ cli: "demo" }, ctx);
    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), [
      "fka-safe-demo",
    ]);
    assertEquals(
      (await Deno.stat(`${root}/bin/fka-safe-demo`)).mode! & 0o777,
      0o755,
    );
    assertEquals(written.find((w) => w.spec === "generated")?.data.removed, []);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("generate takes an alias off PATH once the table stops naming it", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    await model.methods.generate.execute({ cli: "demo" }, fakeCtx(root).ctx);
    // A wrapper from an earlier run, for an alias this table no longer has.
    await Deno.copyFile(
      `${root}/bin/fka-safe-demo`,
      `${root}/bin/fka-write-demo`,
    );

    const { ctx, written } = fakeCtx(root);
    await model.methods.generate.execute({ cli: "demo" }, ctx);
    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), [
      "fka-safe-demo",
    ]);
    assertEquals(written.find((w) => w.spec === "generated")?.data.removed, [
      "fka-write-demo",
    ]);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("remove takes the wrappers off PATH and keeps the judgement", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    await model.methods.generate.execute({ cli: "demo" }, fakeCtx(root).ctx);
    const { ctx, written } = fakeCtx(root);
    await model.methods.remove.execute({ cli: "demo", purge: false }, ctx);

    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), []);
    // The review file survives, so generate rebuilds without a second review.
    assertEquals(
      (await Deno.stat(`${root}/demo/review.yaml`)).isFile,
      true,
    );
    const rec = written.find((w) => w.spec === "removed");
    assertEquals(rec?.data.wrappers, ["fka-safe-demo"]);
    assertEquals(rec?.data.purgedWorkspace, "");
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("remove with purge deletes the review file too", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    await model.methods.generate.execute({ cli: "demo" }, fakeCtx(root).ctx);
    const { ctx, written } = fakeCtx(root);
    await model.methods.remove.execute({ cli: "demo", purge: true }, ctx);

    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demo"), []);
    await assertRejects(() => Deno.stat(`${root}/demo/review.yaml`));
    assertEquals(
      written.find((w) => w.spec === "removed")?.data.purgedWorkspace,
      `${root}/demo`,
    );
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("remove leaves another tool's wrappers alone", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    await model.methods.generate.execute({ cli: "demo" }, fakeCtx(root).ctx);
    // A second tool whose name extends the first. Deleting this would be the
    // prefix bug, with somebody else's grant as the casualty.
    await Deno.copyFile(
      `${root}/bin/fka-safe-demo`,
      `${root}/bin/fka-safe-demolition`,
    );

    await model.methods.remove.execute(
      { cli: "demo", purge: false },
      fakeCtx(root).ctx,
    );
    assertEquals(await ownedWrappers(`${root}/bin`, "fka", "demolition"), [
      "fka-safe-demolition",
    ]);
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("remove says so plainly when there was nothing to remove", async () => {
  const root = await workspaceWith(reviewYaml(true));
  try {
    const { ctx, written, logs } = fakeCtx(root);
    await model.methods.remove.execute({ cli: "demo", purge: false }, ctx);
    assertEquals(written.find((w) => w.spec === "removed")?.data.wrappers, []);
    assert(logs.some((l) => l.includes("No wrappers for demo")));
  } finally {
    await Deno.remove(root, { recursive: true });
  }
});

Deno.test("an executable is replaced whole, never observed half-written", async () => {
  const dir = await Deno.makeTempDir();
  try {
    const path = `${dir}/fka-safe-demo`;
    await writeExecutable(path, "first");
    await writeExecutable(path, "second");
    assertEquals(await Deno.readTextFile(path), "second");
    // The mode is set on the temp, so it is the file's first mode rather than
    // something applied once it is already reachable by name.
    assertEquals((await Deno.stat(path)).mode! & 0o777, 0o755);
    // And nothing is left behind for the next run to trip over.
    const stray: string[] = [];
    for await (const e of Deno.readDir(dir)) stray.push(e.name);
    assertEquals(stray, ["fka-safe-demo"]);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});
