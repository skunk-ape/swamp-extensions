import { assertEquals, assertThrows } from "jsr:@std/assert@1";
import { model, ownedWrappers, workRoot, writeExecutable } from "./fka.ts";

/** The parsed defaults, as a method sees them when nothing overrides. */
function defaults(over: Record<string, unknown> = {}) {
  return model.globalArguments.parse(over);
}

/** Run `body` with the environment temporarily set, restoring whatever was there. */
function withEnv(vars: Record<string, string | null>, body: () => void) {
  const saved = new Map<string, string | undefined>();
  for (const [k, v] of Object.entries(vars)) {
    saved.set(k, Deno.env.get(k));
    if (v === null) Deno.env.delete(k);
    else Deno.env.set(k, v);
  }
  try {
    body();
  } finally {
    for (const [k, v] of saved) {
      if (v === undefined) Deno.env.delete(k);
      else Deno.env.set(k, v);
    }
  }
}

// --- where the workspace lives -------------------------------------------

Deno.test("the workspace defaults to the user's config directory", () => {
  // Not the repository: a wrapper is invoked by bare name, so two repos wrapping
  // one tool would render the same executable name and only one could be on PATH.
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/home/ada/.config/fka");
  });
});

Deno.test("XDG_CONFIG_HOME wins over the home fallback", () => {
  withEnv({ XDG_CONFIG_HOME: "/xdg", HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/xdg/fka");
  });
});

Deno.test("a relative XDG_CONFIG_HOME is ignored rather than trusted", () => {
  // The spec says it must be absolute. Honouring a relative one would put the
  // wrappers somewhere that depends on the working directory of whoever ran the
  // method, which is nobody's intent.
  withEnv({ XDG_CONFIG_HOME: "relative/path", HOME: "/home/ada" }, () => {
    assertEquals(workRoot("/repo", defaults()), "/home/ada/.config/fka");
  });
});

Deno.test("an absolute workRoot is used as given", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(
      workRoot("/repo", defaults({ workRoot: "/opt/fka" })),
      "/opt/fka",
    );
  });
});

Deno.test("a relative workRoot is the project-local escape hatch", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: "/home/ada" }, () => {
    assertEquals(
      workRoot("/repo", defaults({ workRoot: ".fka" })),
      "/repo/.fka",
    );
  });
});

Deno.test("no home and no override refuses rather than guessing", () => {
  withEnv({ XDG_CONFIG_HOME: null, HOME: null }, () => {
    assertThrows(() => workRoot("/repo", defaults()), Error, "workRoot");
  });
});

// --- wrapper ownership and removal ---------------------------------------
//
// `generate` deletes what `ownedWrappers` returns, so both halves of the
// judgement are worth pinning: what counts as ours, and what does not.

/** A file that looks like a rendered wrapper, because it carries the marker. */
async function wrapper(dir: string, name: string) {
  await Deno.writeTextFile(
    `${dir}/${name}`,
    `#!/bin/sh\n// ${name} — generated by @skunk-ape/fka. Do not edit.\n`,
  );
}

Deno.test("a tool owns its own aliases and its qualified ones", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-safe-gh");
    await wrapper(dir, "fka-write-gh");
    await wrapper(dir, "fka-help-gh-pr");
    assertEquals(
      (await ownedWrappers(dir, "fka", "gh")).sort(),
      ["fka-help-gh-pr", "fka-safe-gh", "fka-write-gh"],
    );
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a tool whose name merely extends ours is not ours", async () => {
  // `fka-safe-gh` is a prefix of `fka-safe-ghi`, and `ghi` is a different tool.
  // Getting this wrong deletes somebody else's wrapper.
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-safe-gh");
    await wrapper(dir, "fka-safe-ghi");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), ["fka-safe-gh"]);
    assertEquals(await ownedWrappers(dir, "fka", "ghi"), ["fka-safe-ghi"]);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a file without the marker is left alone whatever it is called", async () => {
  // bin/ is a directory the operator put on their PATH. A name collision with
  // something they wrote is not a reason to delete their file.
  const dir = await Deno.makeTempDir();
  try {
    await Deno.writeTextFile(`${dir}/fka-safe-gh`, "#!/bin/sh\necho mine\n");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), []);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("an unknown segment is not ours, since the segment set is closed", async () => {
  const dir = await Deno.makeTempDir();
  try {
    await wrapper(dir, "fka-mostly-safe-gh");
    assertEquals(await ownedWrappers(dir, "fka", "gh"), []);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});

Deno.test("a missing bin directory is empty rather than an error", async () => {
  assertEquals(await ownedWrappers("/nonexistent-fka-bin", "fka", "gh"), []);
});

Deno.test("an executable is replaced whole, never observed half-written", async () => {
  const dir = await Deno.makeTempDir();
  try {
    const path = `${dir}/fka-safe-demo`;
    await writeExecutable(path, "first");
    await writeExecutable(path, "second");
    assertEquals(await Deno.readTextFile(path), "second");
    // The mode is set on the temp, so it is the file's first mode rather than
    // something applied once it is already reachable by name.
    assertEquals((await Deno.stat(path)).mode! & 0o777, 0o755);
    // And nothing is left behind for the next run to trip over.
    const stray: string[] = [];
    for await (const e of Deno.readDir(dir)) stray.push(e.name);
    assertEquals(stray, ["fka-safe-demo"]);
  } finally {
    await Deno.remove(dir, { recursive: true });
  }
});
